i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: 'en',
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false,
    },
  });

// A French choice stored by an earlier build ('i18nextLng', the key
// i18next-browser-languagedetector uses) is dropped, and the document is English.
try { window.localStorage.removeItem('i18nextLng'); } catch { /* storage blocked: nothing to clean */ }
if (typeof document !== 'undefined') document.documentElement.lang = 'en';

// Strings of the pages rebuilt in October 2026 live in their own module so this
// file stays editable by hand. Deep merge, no overwrite: a key defined above wins.
// Page titles and meta descriptions (the `seo` object) have their own module too;
// no other module defines `seo`, so nothing shadows them.
for (const lng of ['en', 'fr'] as const) {
  i18n.addResourceBundle(lng, 'translation', PAGE_STRINGS[lng], true, false);
  i18n.addResourceBundle(lng, 'translation', SEO_STRINGS[lng], true, false);
  // Refonte brand devices and layout (header, footer, board, route…): src/i18n/brand.ts.
  i18n.addResourceBundle(lng, 'translation', BRAND_STRINGS[lng], true, false);
  // Refonte home page sections (quay figures, profiles, need panel, sponsors, end tiles): src/i18n/home.ts.
  i18n.addResourceBundle(lng, 'translation', HOME_STRINGS[lng], true, false);
  // Refonte events pages (/events, /events/:id): src/i18n/refonte-events.ts.
  i18n.addResourceBundle(lng, 'translation', EVENTS_STRINGS[lng], true, false);
  // Refonte content pages (library, article, About, Contact, Join, legal, 404): src/i18n/refonte-content.ts.
  i18n.addResourceBundle(lng, 'translation', CONTENT_STRINGS[lng], true, false);
  // The refonte directory's strings (src/i18n/directory.ts) are registered by the
  // lazy DirectoryPage itself, so they stay out of the entry bundle.
}

