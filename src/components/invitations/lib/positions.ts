// Words that only a French title would contain (accent-free, lower case). Words shared with
// English ("General Manager", "Executive Vice President", "Commercial Director") are left out:
// with them, only an accent or a French function word marks the title as French.
const FRENCH_WORDS = /\b(directeur|directrice|presidente|responsable|chargee?|gerante?|fondat(eur|rice)|associee?|conseill(er|ere)|ministre|ambassad(eur|rice)|adjointe?|cheffe?|deleguee?|secretaire|developpement|maire|capitaine|ingenieure?|chercheu(r|se)|administrat(eur|rice)|commerciale|generale|du|des|aux|de la|de l|et)\b/;

export interface PositionResult { text: string; translated: boolean; french: boolean }

export function translatePosition(raw: string | null | undefined): PositionResult {
  const text = (raw || '').replace(/\s+/g, ' ').trim();
  if (!text) return { text, translated: false, french: false };
  const k = key(text);
  if (TITLES[k]) return { text: TITLES[k], translated: true, french: false };
  // "Directeur général, Société X" or "Fondateur & PDG": every part known.
  const parts = text.split(/\s*(?:,|&|\bet\b)\s*/i).filter(Boolean);
  if (parts.length > 1 && parts.every(p => TITLES[key(p)])) {
    const joiner = /&|\bet\b/i.test(text) ? ' and ' : ', ';
    return { text: parts.map(p => TITLES[key(p)]).join(joiner), translated: true, french: false };
  }
  const french = FRENCH_WORDS.test(strip(text).toLowerCase()) || /[éèêàçùûôî]/i.test(text);
  return { text, translated: false, french };
}
